package com.galaxyssi.chat

import org.json.JSONArray
import org.json.JSONObject

/** Standing consent is scoped to one concern and a fixed, disclosed model destination. */
internal data class HealthCareResearchAuthorization(val id: String, val scope: HealthCareDiscussionGrant,
    val configuration: String, val revokedAt: Long = 0) {
    init {
        require(HealthProfilePolicy.uuid(id) && configuration.matches(Regex("[0-9a-f]{64}")))
        require(revokedAt >= 0 && scope.researchAuthorizationId.isEmpty())
    }
    val active get() = revokedAt == 0L
    fun permits(grant: HealthCareDiscussionGrant): Boolean = active && grant.researchAuthorizationId == id &&
        scope.concernId == grant.concernId && scope.conversationId == grant.conversationId &&
        scope.settingsVersion == grant.settingsVersion && scope.privacyVersion == grant.privacyVersion &&
        scope.targetId == grant.targetId && scope.modelId == grant.modelId && scope.effort == grant.effort &&
        scope.destination == grant.destination
    fun json() = JSONObject().put("id", id).put("scope", scope.json()).put("configuration", configuration).put("revoked_at", revokedAt)
    companion object { fun from(j: JSONObject) = HealthCareResearchAuthorization(j.getString("id"),
        HealthCareDiscussionGrant.from(j.getJSONObject("scope")), j.getString("configuration"), j.getLong("revoked_at")) }
}

internal enum class HealthCareResearchState { QUEUED, DISPATCHED, COMPLETED, FAILED, CANCELLED, SUPERSEDED }

/** The durable turn identity is reused on recovery, never regenerated by an observer callback. */
internal data class HealthCareResearchJob(val turnId: String, val authorizationId: String, val concernId: String,
    val conversationId: String, val trigger: String, val revision: Int, val createdAt: Long,
    val state: HealthCareResearchState = HealthCareResearchState.QUEUED, val detail: String = "",
    val cancellationPending: Boolean = false) {
    init {
        require(listOf(turnId, authorizationId, concernId, conversationId).all(HealthProfilePolicy::uuid))
        require(trigger.matches(Regex("[0-9a-f]{64}")) && revision > 0 && createdAt > 0 && detail.length <= 2000)
    }
    val terminal get() = state !in setOf(HealthCareResearchState.QUEUED, HealthCareResearchState.DISPATCHED)
    fun json() = JSONObject().put("turn", turnId).put("authorization", authorizationId).put("concern", concernId)
        .put("conversation", conversationId).put("trigger", trigger).put("revision", revision).put("created_at", createdAt)
        .put("state", state.name).put("detail", detail).put("cancel_pending", cancellationPending)
    companion object { fun from(j: JSONObject) = HealthCareResearchJob(j.getString("turn"), j.getString("authorization"),
        j.getString("concern"), j.getString("conversation"), j.getString("trigger"), j.getInt("revision"), j.getLong("created_at"),
        HealthCareResearchState.valueOf(j.getString("state")), j.getString("detail"), j.optBoolean("cancel_pending")) }
}

internal object HealthCareResearchPolicy {
    fun eligible(issue: HealthCareConcern) = issue.open && issue.stage !in setOf(HealthCareStage.PAUSED, HealthCareStage.CLOSED) &&
        issue.assessment.record != null && HealthCareSignal.SOURCE_REMOVED !in issue.assessment.signals

    // Display revisions, conversation binding and pending proposals are not new evidence.
    // A due action enters this key once, not on every scheduler wakeup after its deadline.
    fun trigger(issue: HealthCareConcern, now: Long): String = AgentNativeJsonCodec.sha256(JSONObject()
        .put("basis", HealthCareFollowUpPolicy.basis(issue))
        .put("outcomes", JSONArray(issue.actions.filter { it.state == HealthCareActionState.DONE }.sortedBy { it.id }.map { it.json() }))
        .put("due", JSONArray(issue.actions.filter { it.state == HealthCareActionState.CONFIRMED && it.dueFrom?.let { due -> due <= now } == true }
            .sortedBy { it.id }.map { it.json() })).toString())

    fun transition(before: HealthCareResearchState, after: HealthCareResearchState): Boolean = before == after || when (before) {
        HealthCareResearchState.QUEUED -> after in setOf(HealthCareResearchState.DISPATCHED, HealthCareResearchState.CANCELLED,
            HealthCareResearchState.SUPERSEDED, HealthCareResearchState.FAILED)
        HealthCareResearchState.DISPATCHED -> after != HealthCareResearchState.QUEUED
        else -> false
    }
}
