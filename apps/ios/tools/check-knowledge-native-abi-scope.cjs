const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..', 'memory-native');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const lib = read('src/lib.rs'), owner = read('src/owner.rs'), buffers = read('src/buffers.rs');
const header = read('include/GalaxySSIMemory.h'), manifest = read('Cargo.toml');
const functions = ['open', 'checkpoint', 'begin', 'append', 'search', 'node_count', 'cancel', 'close'];
for (const name of functions) {
  assert.ok(lib.includes(`fn gs_memory_${name}(`), name);
  assert.ok(header.includes(`int32_t gs_memory_${name}(`), name);
}
assert.equal((lib.match(/#\[unsafe\(no_mangle\)\]/g) || []).length, functions.length);
assert.match(lib, /catch_unwind\(AssertUnwindSafe\(call\)\)/);
assert.match(lib, /#\[repr\(C\)\]/);
assert.match(lib, /config.abi_version != 1/);
assert.match(lib, /input\(metadata, metadata_length, 3, 64 \* 3\)/);
assert.match(lib, /Output::prepare\(bytes, capacity, written, 208\)/);
assert.match(lib, /Output::prepare\(bytes, capacity, written, 8 \+ count as usize \* 104\)/);
assert.match(buffers, /written.write\(0\)/);
assert.match(buffers, /mem::align_of::<T>\(\)/);
assert.match(buffers, /isize::MAX/);
assert.match(buffers, /!value.is_finite\(\)/);
assert.match(buffers, /Zeroizing::new/);
assert.match(owner, /AtomicI64::new\(1\)/);
assert.match(owner, /n.checked_add\(1\)/);
assert.match(owner, /\.get\(&id\).cloned\(\)/);
const cancellation = owner.slice(owner.indexOf('pub(crate) fn cancel'));
assert.doesNotMatch(cancellation, /engine.lock/);
assert.match(cancellation, /cancelled.store\(true, Ordering::Release\)/);
assert.match(manifest, /path = "\.\.\/\.\.\/android\/memory-native"/);
assert.match(manifest, /features = \["sqlite-store"\]/);
assert.doesNotMatch(manifest, /android-jni/);
assert.match(manifest, /crate-type = \["cdylib"\]/);
assert.match(manifest, /panic = "unwind"/);
const lock = read('Cargo.lock');
assert.match(lock, /name = "galaxyssi-ios-memory"/);
assert.match(lock, /name = "galaxyssi-memory-native"\nversion = "0.6.0"/);
assert.match(lock, /a2373e82de8b0edea674736e7fa1c2d55b9a9f44/);
assert.equal((read('src/tests.rs').match(/#\[test\]/g) || []).length, 9);
console.log('iOS native knowledge ABI source checks passed; no native build or Rust test execution');
